def situation_bytes(filename: str) -> bytes:
    source = game_root() / "in_game/common/situations" / filename
    rendered, definitions = render_quarantine(
        source, "situations", ("can_start", "visible")
    )
    if definitions != 1:
        raise ValueError(f"{filename}: expected one installed situation, found {definitions}")
    had_bom = rendered.startswith(b"\xef\xbb\xbf")
    text = rendered.decode("utf-8-sig")
    inert_date = AntqDate(*END).engine()

    def clamp(match: re.Match[str]) -> str:
        return inert_date if int(match.group(1)) > END[0] else match.group(0)

    text = re.sub(r"\b(\d{3,4})\.\d{1,2}\.\d{1,2}\b", clamp, text)
    if filename in {"black_death.txt", "great_pestilence.txt"}:
        marker = "\ton_start = {"
        if marker not in text:
            raise ValueError(f"{filename}: installed situation lacks on_start")
        # The installed adapters dereference this engine compatibility variable.
        # Their start and visibility gates are permanently false, so a neutral
        # initializer satisfies the reference graph without activating them.
        text = text.replace(
            marker,
            marker + "\n\t\tset_variable = { name = original_outbreak value = no }",
            1,
        )
    return text.encode("utf-8-sig" if had_bom else "utf-8")


def installed_ducat_entries() -> dict[str, str]:
    entries: dict[str, str] = {}
    for path in sorted((game_root() / "main_menu/localization/english").rglob("*.yml")):
        for line in path.read_text(encoding="utf-8-sig").splitlines():
            match = LOC_LINE.match(line)
            if match and re.search(r"\bducats?\b", match.group(2), re.IGNORECASE):
                entries[match.group(1)] = match.group(2)
    return entries


def currency_entries() -> dict[str, str]:
    entries = installed_ducat_entries()
    rewritten: dict[str, str] = {}
    for key, value in entries.items():
        value = re.sub(r"\bducats?\b", "wealth", value, flags=re.IGNORECASE)
        if FORBIDDEN_CURRENCY_CONTEXT.search(value):
            if key.endswith("historical_info"):
                value = "This agreement records a transfer of wealth between the participating states."
            elif key.endswith("_desc"):
                value = "Accounts, appointed scribes, and audited stores improve the state's control of wealth."
            else:
                value = "Wealth"
        rewritten[key] = value
    rewritten["gold"] = "Wealth"
    rewritten["game_concept_gold"] = "Wealth"
    rewritten["game_concept_gold_desc"] = (
        "A universal measure of liquid wealth: coin, weighed metal, valuables, "
        "and trusted accounting claims. A country's current reserve is its "
        "[treasury|e].\\n\\nWealth comes from [taxes|e], [estates|e], [subjects|e], "
        "and exchange, and pays for [buildings|e], [armies|e], food, goods, "
        "diplomacy, and the [court|e]."
    )
    return rewritten


def disease_loc() -> dict[str, str]:
    values: dict[str, str] = {}
    for disease in (*DISEASES, MALARIA):
        values[disease.key] = disease.name
        values[f"{disease.key}_desc"] = disease.description
        values[f"{disease.key}_location_modifier"] = f"{disease.name} burden"
        values[f"local_{disease.key}_impact_modifier"] = f"{disease.name} impact"
    return values


def loc_bytes(client: str) -> bytes:
    lines = [f"l_{client}:"]
    for key, value in sorted({**currency_entries(), **disease_loc()}.items()):
        escaped = value.replace('"', '\\"')
        lines.append(f' {key}: "{escaped}"')
    return ("\n".join(lines) + "\n").encode("utf-8-sig")


def write() -> None:
    DISEASE_DIR.mkdir(parents=True, exist_ok=True)
    expected_diseases = set(installed_files("in_game/common/diseases"))
    rendered = {disease.key + ".txt": render_epidemic(disease) for disease in DISEASES}
    rendered["malaria.txt"] = render_malaria()
    if set(rendered) != expected_diseases:
        raise ValueError(f"disease file union changed: {sorted(expected_diseases ^ set(rendered))}")
    for filename, text in rendered.items():
        (DISEASE_DIR / filename).write_bytes(text.encode("utf-8-sig"))

    SITUATION_DIR.mkdir(parents=True, exist_ok=True)
    for filename in installed_files("in_game/common/situations"):
        (SITUATION_DIR / filename).write_bytes(situation_bytes(filename))

    for client in CLIENTS:
        path = LOC_ROOT / client / f"antq_r5_visible_unions_l_{client}.yml"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(loc_bytes(client))
    print("r5_visible_unions: wrote 7 diseases, 22 inert situation adapters, and 11 localization mirrors")


def effective_mod_loc(client: str) -> dict[str, str]:
    values: dict[str, str] = {}
    for path in sorted((LOC_ROOT / client).rglob("*.yml")):
        for line in path.read_text(encoding="utf-8-sig").splitlines():
            match = LOC_LINE.match(line)
            if match:
                values[match.group(1)] = match.group(2)
    return values


def validate() -> None:
    failures: list[str] = []
    expected_diseases = set(installed_files("in_game/common/diseases"))
    actual_diseases = {path.name for path in DISEASE_DIR.glob("*.txt")}
    if actual_diseases != expected_diseases:
        failures.append(f"disease files differ from installed union: {sorted(actual_diseases ^ expected_diseases)}")
    for path in sorted(DISEASE_DIR.glob("*.txt")):
        if not path.read_bytes().startswith(b"\xef\xbb\xbf"):
            failures.append(f"{path}: disease script is not UTF-8 BOM")
        text = path.read_text(encoding="utf-8-sig")
        definitions = TOP_LEVEL.findall(text)
        if definitions != [path.stem]:
            failures.append(f"{path}: definitions {definitions} != [{path.stem}]")
        scan_text = text
        compatibility_event = COMPATIBILITY_EVENTS.get(path.stem)
        if compatibility_event:
            inert_reference = (
                "\t\tif = { limit = { always = no } "
                f"trigger_event_non_silently = {compatibility_event} }}"
            )
            if text.count(inert_reference) != 1:
                failures.append(f"{path}: missing exact inert compatibility-event reference")
            scan_text = scan_text.replace(inert_reference, "", 1)
        forbidden = FORBIDDEN_DISEASE.search(scan_text)
        if forbidden:
            failures.append(f"{path}: forbidden inherited disease token {forbidden.group(0)!r}")
        for required in ("mortality_rate", "location_modifier", "map_color", "calc_interval_days"):
            if required not in text:
                failures.append(f"{path}: missing {required}")

    installed_situations = set(installed_files("in_game/common/situations"))
    for filename in sorted(installed_situations):
        path = SITUATION_DIR / filename
        expected = situation_bytes(filename)
        if not path.is_file() or path.read_bytes() != expected:
            failures.append(f"inherited situation adapter is stale: {filename}")
        elif TOP_LEVEL.findall(path.read_text(encoding="utf-8-sig")) != [Path(filename).stem]:
            failures.append(f"inherited situation adapter lost its registry key: {filename}")
    custom_ids: set[str] = set()
    for path in SITUATION_DIR.glob("antq*.txt"):
        custom_ids.update(TOP_LEVEL.findall(path.read_text(encoding="utf-8-sig")))
    if len(custom_ids) != 43:
        failures.append(f"expected 43 ancient situations, found {len(custom_ids)}")

    ducat_keys = set(installed_ducat_entries())
    expected_currency = currency_entries()
    reference: bytes | None = None
    for client in CLIENTS:
        path = LOC_ROOT / client / f"antq_r5_visible_unions_l_{client}.yml"
        expected = loc_bytes(client)
        if not path.is_file() or path.read_bytes() != expected:
            failures.append(f"stale Round 5 localization mirror: {path}")
        normalized = expected.replace(f"l_{client}:".encode(), b"l_CLIENT:")
        if reference is None:
            reference = normalized
        elif normalized != reference:
            failures.append(f"client localization diverges: {client}")
        loc = effective_mod_loc(client)
        missing_currency = sorted((ducat_keys | {"gold", "game_concept_gold", "game_concept_gold_desc"}) - set(loc))
        if missing_currency:
            failures.append(f"{client}: missing Wealth overrides {missing_currency}")
        if any(re.search(r"\bducats?\b", loc[key], re.IGNORECASE) for key in expected_currency):
            failures.append(f"{client}: Ducats survives a Wealth override")
        for situation in custom_ids:
            if situation not in loc or f"{situation}_desc" not in loc:
                failures.append(f"{client}: missing situation title/description for {situation}")
        for disease in (*DISEASES, MALARIA):
            if loc.get(disease.key) != disease.name or loc.get(f"{disease.key}_desc") != disease.description:
                failures.append(f"{client}: stale disease localization for {disease.key}")
    if failures:
        raise ValueError("\n  - ".join(["Round 5 visible-union validation failed", *failures]))
    print(f"r5_visible_unions: PASS (7 diseases; 22 inert adapters; 43 ancient situations; {len(ducat_keys)} Wealth overrides; 11 clients)")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write:
        write()
    if args.check or not args.write:
        validate()
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, UnicodeError, ValueError) as exc:
        print(f"r5_visible_unions: FAIL\n  - {exc}", file=sys.stderr)
        raise SystemExit(1)
