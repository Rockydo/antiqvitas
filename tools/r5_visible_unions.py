def game_root() -> Path:
    return Path(json.loads(CONFIG.read_text(encoding="utf-8-sig"))["game_dir"]) / "game"


def installed_files(relative: str) -> tuple[str, ...]:
    directory = game_root() / relative
    return tuple(sorted(path.name for path in directory.glob("*.txt") if path.name != "readme.txt"))


