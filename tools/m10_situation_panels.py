def outputs() -> dict[Path, str]:
    result = {PANEL_DIR / f"{key}.gui": panel_script(key) for key in situation_keys()}
    result[COMMON_OUTPUT] = common_panel_script()
    return result


def write() -> None:
    for path, content in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


def check() -> None:
    expected = outputs()
    missing = [str(path.relative_to(ROOT)) for path, content in expected.items() if not path.is_file() or path.read_text(encoding="utf-8-sig") != content]
    unexpected = sorted(path.name for path in PANEL_DIR.glob("antq_*.gui") if path not in expected)
    if missing or unexpected:
        raise ValueError(f"situation panel drift: missing_or_changed={missing}, unexpected={unexpected}")
    for path, content in expected.items():
        if path == COMMON_OUTPUT:
            for token in ("SituationView.GetActiveSituation.GetName]", "TooltipRequirementsList"):
                if token not in content:
                    raise ValueError(f"{path.name} lacks generic situation-panel token {token}")
            continue
        for token in ("situation_panel_main_content", "TooltipRequirementsList", "situation_disaster_progressbar_with_thresholds"):
            if token not in content:
                raise ValueError(f"{path.name} lacks standard panel token {token}")
    print(f"m10_situation_panels: PASS ({len(expected)} readable situation panels)")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write:
        write()
        print(f"m10_situation_panels: wrote {len(outputs())} panels")
    if args.check or not args.write:
        check()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
