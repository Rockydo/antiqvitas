#!/usr/bin/env python3
"""Generate the shared readable panel layout for every ANTIQVITAS situation."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SITUATION_DIR = ROOT / "in_game/common/situations"
PANEL_DIR = ROOT / "in_game/gui/panels/situation"
EVENT_ART_DIR = ROOT / "main_menu/gfx/interface/illustrations/event"
FALLBACK_ART = "gfx/interface/illustrations/situation/antq_m10_immensum_bellum.dds"
CONFIG = ROOT / "config/local_paths.json"
COMMON_RELATIVE = Path("game/in_game/gui/panels/situation/common.gui")
COMMON_OUTPUT = PANEL_DIR / "common.gui"
COMMON_SHA256 = "8b5b0ed89f86a0890a5aba512934205e093360d40a4a5a11f52b3dd2e353a35c"


def common_panel_script() -> str:
    game_dir = Path(json.loads(CONFIG.read_text(encoding="utf-8"))["game_dir"])
    source = (game_dir / COMMON_RELATIVE).read_text(encoding="utf-8-sig")
    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    if digest != COMMON_SHA256:
        raise ValueError(f"installed common situation panel changed: {digest}")
    marker = '\t\t\t\t\t\t\t\t\tblock "situation_panel_main_content" {}'
    generic_content = '''\t\t\t\t\t\t\t\t\tblock "situation_panel_main_content" {
\t\t\t\t\t\t\t\t\t\tvbox = {
\t\t\t\t\t\t\t\t\t\t\tlayoutpolicy_horizontal = expanding
\t\t\t\t\t\t\t\t\t\t\tmargin = { 10 10 }
\t\t\t\t\t\t\t\t\t\t\tspacing = 6
\t\t\t\t\t\t\t\t\t\t\ttext_single = {
\t\t\t\t\t\t\t\t\t\t\t\tlayoutpolicy_horizontal = expanding
\t\t\t\t\t\t\t\t\t\t\t\talign = center
\t\t\t\t\t\t\t\t\t\t\t\ttext = "[SituationView.GetActiveSituation.GetName]"
\t\t\t\t\t\t\t\t\t\t\t\tdefault_format = "#header_titles"
\t\t\t\t\t\t\t\t\t\t\t}
\t\t\t\t\t\t\t\t\t\t\tsituation_card_expandable = {
\t\t\t\t\t\t\t\t\t\t\t\tblockoverride "header_button_onclick" {
\t\t\t\t\t\t\t\t\t\t\t\t\tonclick = "[LateralView.Vars.Toggle( 'requirements_toggled' )]"
\t\t\t\t\t\t\t\t\t\t\t\t}
\t\t\t\t\t\t\t\t\t\t\t\tblockoverride "header_text" { text = "END_REQUIREMENTS" }
\t\t\t\t\t\t\t\t\t\t\t\tblockoverride "header_icon" { texture = "gfx/interface/icons/disasters/end_requirements_green.dds" }
\t\t\t\t\t\t\t\t\t\t\t\tblockoverride "bottom_content" {
\t\t\t\t\t\t\t\t\t\t\t\t\tTooltipRequirementsList = {
\t\t\t\t\t\t\t\t\t\t\t\t\t\ttextcontext = "[SituationView.GetActiveSituation.GetSituation.GetEndConditions]"
\t\t\t\t\t\t\t\t\t\t\t\t\t}
\t\t\t\t\t\t\t\t\t\t\t\t}
\t\t\t\t\t\t\t\t\t\t\t}
\t\t\t\t\t\t\t\t\t\t}
\t\t\t\t\t\t\t\t\t}'''
    if source.count(marker) != 1:
        raise ValueError("installed common situation panel has no unique main-content marker")
    rendered = source.replace(marker, generic_content)
    # Canonicalize whitespace in the generated overlay so the file participates
    # cleanly in repository diff checks without changing its GUI semantics.
    return "\n".join(line.rstrip() for line in rendered.splitlines()) + "\n"


def situation_keys() -> tuple[str, ...]:
    keys: list[str] = []
    for path in sorted(SITUATION_DIR.glob("antq_*.txt")):
        keys.extend(re.findall(r"(?m)^(antq_[a-z0-9_]+)\s*=\s*\{", path.read_text(encoding="utf-8-sig")))
    if len(keys) != len(set(keys)):
        raise ValueError("ancient situation keys are not unique")
    if len(keys) != 43:
        raise ValueError(f"expected 43 ancient situations, found {len(keys)}")
    return tuple(keys)


def illustration(key: str) -> str:
    event_name = key.removeprefix("antq_m10_")
    candidate = EVENT_ART_DIR / f"antq_{event_name}.dds"
    if candidate.is_file():
        return f"gfx/interface/illustrations/event/{candidate.name}"
    return FALLBACK_ART


